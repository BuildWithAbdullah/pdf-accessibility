// Generates CATALOGUE.md from lib/catalogue.mjs.
//
// The write is guarded so importing this module has no side effect, which lets
// tools/verify.mjs compare the generated text against the file on disk rather
// than regenerating it and then reading back what it has just written. A
// checker that runs the generator before reading always passes.
//
// The status line goes to stderr, so a CI step may redirect stdout without
// capturing npm's own banner into the content.

import { writeFileSync, readFileSync, realpathSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, resolve } from 'node:path'
import { CATALOGUE } from '../lib/catalogue.mjs'
import { RULES } from '../lib/rules/index.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const target = join(resolve(here, '..'), 'CATALOGUE.md')

export function buildCatalogue () {
  const lines = []
  lines.push('# Catalogue')
  lines.push('')
  lines.push('Generated by `tools/build-catalogue.mjs` from `lib/catalogue.mjs`. Do not edit by hand:')
  lines.push('CI regenerates it and fails if the result differs from this file.')
  lines.push('')
  lines.push('One entry per reason a check can fire, not one per check. Each entry says what the')
  lines.push('defect is, what it costs a reader, what the fix is, and what the finding cannot')
  lines.push('establish. Entries marked **source** cannot be repaired in the PDF at all.')
  lines.push('')
  lines.push(CATALOGUE.length + ' findings across ' + RULES.length + ' rules.')
  lines.push('')

  for (const rule of RULES) {
    const entries = CATALOGUE.filter((entry) => entry.rule === rule.id)
    lines.push('## ' + rule.id)
    lines.push('')
    lines.push(rule.title + '.')
    lines.push('')
    for (const entry of entries) {
      lines.push('### `' + entry.id + '`' + (entry.needsSource ? ' **source**' : ''))
      lines.push('')
      lines.push('**' + entry.title + '**')
      lines.push('')
      lines.push(entry.why)
      lines.push('')
      lines.push('*Fix.* ' + entry.fix)
      lines.push('')
      lines.push('*What this finding cannot establish.* ' + entry.limit)
      lines.push('')
    }
  }
  return lines.join('\n')
}

export function catalogueOnDisk () {
  return readFileSync(target, 'utf8')
}

export { target as CATALOGUE_PATH }

if (realpathSync(process.argv[1] || '') === realpathSync(fileURLToPath(import.meta.url))) {
  const text = buildCatalogue()
  writeFileSync(target, text)
  process.stderr.write('wrote CATALOGUE.md, ' + text.split('\n').length + ' lines\n')
}
