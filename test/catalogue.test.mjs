import { test } from 'node:test'
import assert from 'node:assert/strict'
import { CATALOGUE, CATALOGUE_BY_ID, FINDING_IDS, NEEDS_SOURCE_IDS, duplicateIds } from '../lib/catalogue.mjs'
import { RULES, RULES_BY_ID } from '../lib/rules/index.mjs'
import { buildCatalogue, catalogueOnDisk } from '../tools/build-catalogue.mjs'

test('no two findings share an id', () => {
  assert.deepEqual(duplicateIds(), [])
})

test('every finding id is prefixed by something that reads as a subject', () => {
  for (const id of FINDING_IDS) {
    assert.match(id, /^[a-z]+(\.[a-z-]+)+$/, id)
  }
})

test('every finding belongs to a rule that exists', () => {
  for (const entry of CATALOGUE) assert.ok(RULES_BY_ID.has(entry.rule), entry.id)
})

test('every rule contributes at least one finding', () => {
  for (const rule of RULES) {
    assert.ok(CATALOGUE.some((entry) => entry.rule === rule.id), rule.id)
  }
})

test('every finding states what it cannot establish', () => {
  for (const entry of CATALOGUE) {
    assert.ok(entry.limit.length > 40, entry.id + ' has no statement of its limit')
    assert.notEqual(entry.limit, entry.why, entry.id)
  }
})

test('every finding states a fix that differs from its description', () => {
  for (const entry of CATALOGUE) {
    assert.notEqual(entry.fix, entry.title, entry.id)
    assert.notEqual(entry.fix, entry.why, entry.id)
  }
})

test('the three findings whose fix is outside the PDF are the ones declared', () => {
  assert.deepEqual([...NEEDS_SOURCE_IDS].sort(), ['text.as.paths', 'text.layer.absent', 'text.unicode.unmappable'])
})

test('the catalogue on disk matches what the builder produces', () => {
  // Compared against the builder, not regenerated by this test. A check that
  // runs the generator and then reads the file always passes, because it has
  // just written the thing it is checking.
  assert.equal(catalogueOnDisk(), buildCatalogue())
})

test('the generated catalogue holds every finding id', () => {
  const text = buildCatalogue()
  for (const id of FINDING_IDS) assert.ok(text.includes('`' + id + '`'), id)
})

test('lookup by id returns the same objects the list holds', () => {
  for (const entry of CATALOGUE) assert.equal(CATALOGUE_BY_ID.get(entry.id), entry)
})

test('a rule reporting a finding outside the catalogue is refused', async () => {
  const { auditModel } = await import('../lib/audit.mjs')
  const fake = { id: 'invented', title: 'x'.repeat(30), findings: {}, check: () => [{ id: 'not.in.catalogue' }] }
  RULES.push(fake)
  try {
    assert.throws(() => auditModel({ nodes: [], pages: [], file: null, roleMap: {} }), /not in the catalogue/)
  } finally {
    RULES.pop()
  }
})
